const CHAR_W: usize = 6;
const CHAR_H: usize = 9;

/// An RGBA8 image.
pub struct Image {
    pub width: usize,
    pub height: usize,
    pub rgba: Vec<u8>,
}

/// Render `text` on a padded background box, `scale` pixels per font dot.
pub fn render(text: &str, scale: usize, fg: [u8; 4], bg: [u8; 4]) -> Image {
    let scale = scale.max(1);
    let n = text.chars().count();
    let width = (n * CHAR_W + CHAR_W) * scale;
    let height = (CHAR_H * 2) * scale;
    let mut rgba = Vec::with_capacity(width * height * 4);
    for _ in 0..width * height {
        rgba.extend_from_slice(&bg);
    }
    let x0 = CHAR_W * scale / 2;
    let y0 = CHAR_H * scale / 2;
    for (ci, ch) in text.chars().enumerate() {
        for (row, bits) in glyph(ch).iter().enumerate() {
            for col in 0..5 {
                if (bits >> (4 - col)) & 1 == 0 {
                    continue;
                }
                let px = x0 + (ci * CHAR_W + col) * scale;
                let py = y0 + row * scale;
                for sy in 0..scale {
                    let start = ((py + sy) * width + px) * 4;
                    for sx in 0..scale {
                        rgba[start + sx * 4..start + sx * 4 + 4].copy_from_slice(&fg);
                    }
                }
            }
        }
    }
    Image { width, height, rgba }
}

#[cfg(test)]
mod tests {
    #[test]
    fn renders_box_of_expected_size() {
        let img = super::render("AB", 2, [255; 4], [0; 4]);
        assert_eq!(img.width, (2 * 6 + 6) * 2);
        assert_eq!(img.height, 18 * 2);
        assert_eq!(img.rgba.len(), img.width * img.height * 4);
        assert!(img.rgba.chunks(4).any(|p| p == [255; 4]));
    }
}
